# Regular print
print ("Hello everybody")

# \t (tab) before the string
print ("\tHello everybody")

# \t (tab) before and in between the string
print ("\tHello\teverybody")

# null
print()

# \n for new line
print("\n")

# Line break in between the string
print ("Hello\neverybody")

# \ for exceptions in a string
print ("\"Hello\" everybody")

